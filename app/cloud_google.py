"""Google adapters. Credentials and upload sessions never enter log messages."""
import copy
import datetime
import os
import threading

import google.auth
from google.auth.transport.requests import Request
from google.api_core.exceptions import AlreadyExists, NotFound, PreconditionFailed
from google.cloud import firestore, storage, tasks_v2
from google.cloud.firestore_v1.base_query import FieldFilter
import httpx

from cloud_state import CloudJobs, Rejected
import settings

PPTX = 'application/vnd.openxmlformats-officedocument.presentationml.presentation'


class FirestoreRepo:
    def __init__(self, project, credentials=None):
        self.db = firestore.Client(project=project, credentials=credentials)

    def get(self, key):
        return self.db.document(key).get(timeout=20).to_dict()

    def atomic(self, keys, operation):
        refs = {key: self.db.document(key) for key in keys}
        @firestore.transactional
        def run(tx):
            values = {key: ref.get(transaction=tx, timeout=20).to_dict() for key, ref in refs.items()}
            before = copy.deepcopy(values)
            result = operation(values)
            for key, value in values.items():
                if value != before[key]:
                    if value is None:
                        tx.delete(refs[key])
                    else:
                        tx.set(refs[key], value)
            return result
        return run(self.db.transaction(max_attempts=8))

    def query(self, collection, field, value):
        return [s.to_dict() for s in self.db.collection(collection).where(filter=FieldFilter(field, '==', value)).stream(timeout=30)]

    def active(self):
        return [s.to_dict() for s in self.db.collection('jobs').where(filter=FieldFilter('state', 'in', ['queued', 'running', 'publishing', 'retrying'])).stream(timeout=30)]

    def expired(self, now):
        return [s.to_dict() for s in self.db.collection('jobs').where(filter=FieldFilter('expires_at', '<=', now)).stream(timeout=30)]


class Objects:
    def __init__(self, project, bucket, signer, credentials=None):
        self.client = storage.Client(project=project, credentials=credentials)
        self.bucket = self.client.bucket(bucket)
        self.signer = signer
        self.credentials = credentials or google.auth.default(scopes=['https://www.googleapis.com/auth/cloud-platform'])[0]
        self.lock = threading.Lock()

    def metadata(self, key):
        blob = self.bucket.get_blob(key, timeout=20)
        return None if blob is None else {'generation': int(blob.generation), 'size': int(blob.size), 'md5': blob.md5_hash}

    def session(self, key, size):
        blob = self.bucket.blob(key)
        blob.metadata = {'temporary': 'true'}
        return blob.create_resumable_upload_session(content_type=PPTX, size=size,
                    if_generation_match=0, timeout=20)

    def cancel(self, session):
        if not session:
            return
        # The URL was generated by the storage SDK, not supplied by the caller.
        with httpx.Client(timeout=15, trust_env=False, follow_redirects=False) as client:
            response = client.delete(session, headers={'Content-Length': '0'})
        if response.status_code not in (200, 204, 400, 404, 410, 499):
            raise RuntimeError('Could not cancel an upload.')

    def fence(self, key):
        # An atomic zero-byte replacement closes generation=0 sessions even if
        # cancellation response was ambiguous. Keep tombstones beyond 7 days.
        for _ in range(8):
            current = self.bucket.get_blob(key, timeout=20)
            if current and current.size == 0 and (current.metadata or {}).get('fence') == 'true':
                return
            target = self.bucket.blob(key)
            target.metadata = {'fence': 'true', 'temporary': 'true'}
            try:
                target.upload_from_string(b'', if_generation_match=int(current.generation) if current else 0, timeout=20)
                return
            except PreconditionFailed:
                continue
        raise RuntimeError('Could not fence an upload.')

    def promote(self, key, generation, final):
        source = self.bucket.blob(key, generation=generation)
        try:
            self.bucket.copy_blob(source, self.bucket, new_name=final,
                                  if_generation_match=0, if_source_generation_match=generation, timeout=30)
        except PreconditionFailed:
            # A retried copy can observe its already-created destination. The
            # protocol verifies size/hash and the current fencing token next.
            pass
        result = self.metadata(final)
        if result is None:
            raise Rejected('The result could not be saved.')
        return result

    def signed_get(self, key, generation, deadline, filename):
        with self.lock:
            if not self.credentials.valid:
                self.credentials.refresh(Request())
            token = self.credentials.token
        return self.bucket.blob(key, generation=generation).generate_signed_url(
            version='v4', expiration=datetime.datetime.fromtimestamp(deadline, datetime.timezone.utc), method='GET',
            service_account_email=self.signer, access_token=token,
            response_disposition=f'attachment; filename="{filename}"',
            query_parameters={'generation': str(generation)})

    def read(self, key, generation):
        return self.bucket.blob(key, generation=generation).download_as_bytes(timeout=30)

    def stream(self, key, generation):
        with self.bucket.blob(key, generation=generation).open('rb', chunk_size=256*1024, timeout=30) as handle:
            while chunk := handle.read(256*1024):
                yield chunk


class Queue:
    def __init__(self, project, location, name, worker, invoker):
        self.client = tasks_v2.CloudTasksClient()
        self.parent = self.client.queue_path(project, location, name)
        self.worker, self.invoker = worker.rstrip('/'), invoker

    def enqueue(self, jid, capability):
        import json
        request = tasks_v2.HttpRequest(
            http_method=tasks_v2.HttpMethod.POST, url=self.worker+'/execute',
            headers={'Content-Type': 'application/json'},
            body=json.dumps({'job_id': jid, 'credential': capability}).encode(),
            oidc_token=tasks_v2.OidcToken(service_account_email=self.invoker, audience=self.worker))
        task = tasks_v2.Task(name=self.parent+'/tasks/'+jid, http_request=request,
                             dispatch_deadline={'seconds': 600})
        try:
            self.client.create_task(parent=self.parent, task=task, timeout=20)
        except AlreadyExists:
            pass


def build():
    project = os.environ['GOOGLE_CLOUD_PROJECT']
    return CloudJobs(FirestoreRepo(project),
        Objects(project, os.environ['RESULT_BUCKET'], os.environ['DOWNLOAD_SIGNER']),
        Queue(project, os.environ['CLOUD_REGION'], os.environ['TASK_QUEUE'],
              os.environ['WORKER_URL'], os.environ['TASK_INVOKER']),
        (os.environ.get('LINK_KEY') or os.environ['API_TOKEN']).encode(), settings.LIMITS,
        max_active=settings.MAX_ACTIVE, max_data_mb=settings.MAX_DATA_MB)
